use std::{env, fs, path::PathBuf};

use specta_typescript::Typescript;

fn compact_typescript(source: &str) -> String {
    source
        .split("\n\n")
        .map(|block| {
            if block.trim_start().starts_with("//") {
                block.trim().to_string()
            } else {
                block.split_whitespace().collect::<Vec<_>>().join(" ")
            }
        })
        .collect::<Vec<_>>()
        .join("\n\n")
}

fn main() {
    let mut args = env::args().skip(1);
    let output = args
        .next()
        .map(PathBuf::from)
        .expect("usage: export-types <output-file> [--check]");
    let check = args.any(|argument| argument == "--check");
    let generated = Typescript::default()
        .export(&hachimi_protocol::registered_types(), specta_serde::Format)
        .expect("failed to render TypeScript contracts");
    let generated = compact_typescript(&generated)
        // `density` is required in the resolved public contract. Rust keeps
        // serde(default) on the field so legacy settings files still load.
        .replace("density?: UiDensity", "density: UiDensity");
    let contents = format!("// @generated by hachimi-protocol. Do not edit.\n\n{generated}\n");

    if check {
        let existing = fs::read_to_string(&output).expect("generated contract file is missing");
        assert_eq!(
            existing, contents,
            "generated TypeScript contracts are stale"
        );
    } else {
        if let Some(parent) = output.parent() {
            fs::create_dir_all(parent).expect("failed to create contract output directory");
        }
        fs::write(output, contents).expect("failed to write TypeScript contracts");
    }
}
